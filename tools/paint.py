#!/usr/bin/env python3
"""The PAINTED look's skies: renders/painted/src/*.jpg (1536x1024, gpt-image-2.5 via Codex) -> app/paint.h.

Each is cropped to 5:3, shrunk to the sky (240x144), ordered-dithered to RGB565 with ImageMagick, and written
as the panel's bytes (RGB565 big-endian, what cv_px holds), so the look copies a row and draws on top.
  tools/paint.py            (needs `magick` on PATH)"""
import pathlib
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "renders/painted/src"
OUT = ROOT / "app/paint.h"
NAMES = ["redwood_dusk", "redwood_dawn", "cosmic_rings", "coast_aurora"]   # the order of PAINT_*
W, H = 240, 144


def rgb565(name):
    raw = subprocess.run(
        ["magick", str(SRC / f"{name}.jpg"), "-gravity", "center", "-crop", "1536x922+0+0", "+repage",
         "-filter", "Lanczos", "-resize", f"{W}x{H}!", "-ordered-dither", "o4x4,32,64,32", "-depth", "8", "rgb:-"],
        check=True, capture_output=True).stdout
    assert len(raw) == W * H * 3, (name, len(raw))
    out = bytearray()
    for i in range(0, len(raw), 3):
        r, g, b = (raw[i] * 31 + 127) // 255, (raw[i + 1] * 63 + 127) // 255, (raw[i + 2] * 31 + 127) // 255
        c = (r << 11) | (g << 5) | b
        out += bytes((c >> 8, c & 0xFF))
    return bytes(out)


def main():
    lines = ["/* Generated by tools/paint.py from renders/painted/src: do not edit. */",
             f"#define PAINT_W {W}", f"#define PAINT_H {H}", f"#define NPAINT {len(NAMES)}"]
    lines += [f"#define PAINT_{n.upper()} {i}" for i, n in enumerate(NAMES)]
    lines.append(f"static const uint8_t PAINT[NPAINT][PAINT_W * PAINT_H * 2] __attribute__((aligned(4))) = {{")
    for n in NAMES:
        b = rgb565(n)
        lines.append(f"    {{ /* {n} */")
        for i in range(0, len(b), 32):
            lines.append("        " + ",".join(str(x) for x in b[i:i + 32]) + ",")
        lines.append("    },")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{OUT.relative_to(ROOT)}: {len(NAMES)} skies, {len(NAMES) * W * H * 2} bytes")


if __name__ == "__main__":
    main()
